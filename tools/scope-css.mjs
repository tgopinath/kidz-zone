// One-time tool: scope a world's global stylesheet under its wrapper class, so worlds that share class names
// (.btn, .card, .page…) never clash. `:root`, `html` and `body` become the wrapper itself; app-mode prefixes
// (html.k-android, html.k-ios) stay on <html>. Usage: node tools/scope-css.mjs <in.css> <out.css> <.scope>
import fs from 'node:fs';
import postcss from 'postcss';
import prefixer from 'postcss-prefix-selector';

const [, , input, output, scope] = process.argv;
let css = fs.readFileSync(input, 'utf8');
// Keyframe names are global too: suffix them with the scope name (and their uses in this file).
const tag = scope.replace(/^\./, '');
const names = [...css.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]);
for (const n of new Set(names)) css = css.replace(new RegExp(`(@keyframes\\s+|animation(?:-name)?\\s*:[^;}]*?)\\b${n}\\b`, 'g'), `$1${n}-${tag}`);
const out = await postcss([
  prefixer({
    prefix: scope,
    transform(prefix, selector) {
      let s = selector.trim();
      const m = s.match(/^html((?:\.[\w-]+|:is\([^)]*\)|:not\([^)]*\))+)\s*(.*)$/);
      if (m) {
        const rest = m[2].replace(/^body\b\s*/, '');
        return `html${m[1]} ${prefix}${rest ? ' ' + rest : ''}`;
      }
      if (/^(:root|html|body)\b/.test(s)) return s.replace(/^(:root|html|body)(\s+body)?/, prefix);
      if (/^\[data-theme/.test(s)) return `${prefix}${s}`;
      return `${prefix} ${s}`;
    },
  }),
]).process(css, { from: input });
fs.writeFileSync(output, `/* Generated by tools/scope-css.mjs from ${input.split('/').pop()}; scoped under ${scope}. */\n` + out.css);
console.log('scoped', input, '->', output);
