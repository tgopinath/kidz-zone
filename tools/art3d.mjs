// Builds the 3D picture set: finds every emoji the app's source uses, copies the matching Microsoft Fluent Emoji 3D
// picture (MIT, 256 px WebP from the npm package @lobehub/fluent-emoji-3d) into public/art3d/, and writes
// src/play/art3d.generated.ts (the list of emoji that have a picture). Only pictures actually used are shipped.
//   node tools/art3d.mjs <path to the unpacked package's assets folder>
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = process.argv[2];
if (!SRC || !fs.existsSync(SRC)) { console.error('usage: node tools/art3d.mjs <fluent-emoji-3d/assets>'); process.exit(1); }
const OUT = path.join(ROOT, 'public/art3d');
const have = new Set(fs.readdirSync(SRC).filter((f) => f.endsWith('.webp')).map((f) => f.slice(0, -5)));

const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else if (/\.(tsx?|js|json)$/.test(f.name) && !/generated|\.test\./.test(f.name)) files.push(p); } };
walk(path.join(ROOT, 'src'));
for (const extra of ['public/garden/img/index.json']) if (fs.existsSync(path.join(ROOT, extra))) files.push(path.join(ROOT, extra));

const re = /\p{RGI_Emoji}/gv;
const used = new Map();
for (const f of files) for (const m of fs.readFileSync(f, 'utf8').matchAll(re)) used.set(m[0], (used.get(m[0]) || 0) + 1);
// Map Explorer builds flags from ISO codes at run time (src/worlds/maps/lib/world.ts flagOf)
const world = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/worlds/maps/data/generated/world-index.json'), 'utf8'));
for (const c of world.countries) if (/^[A-Z]{2}$/.test(c.iso2 || '')) { const f = String.fromCodePoint(...[...c.iso2].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65)); used.set(f, (used.get(f) || 0) + 1); }

export const codes = (e) => [...e].map((c) => c.codePointAt(0).toString(16));
function fileFor(e) {
  const c = codes(e);
  const tries = [c.join('-'), c.filter((x) => x !== 'fe0f').join('-'), [...c, 'fe0f'].join('-')];
  // keycaps and sequences that lost fe0f in the middle
  if (c.length === 2 && c[1] === '20e3') tries.push(`${c[0]}-fe0f-20e3`);
  return tries.find((t) => have.has(t));
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const map = {};
const missing = [];
for (const [e] of [...used].sort((a, b) => b[1] - a[1])) {
  const f = fileFor(e);
  if (!f) { missing.push(e); continue; }
  map[e] = f;
  if (!fs.existsSync(path.join(OUT, f + '.webp'))) fs.copyFileSync(path.join(SRC, f + '.webp'), path.join(OUT, f + '.webp'));
}
const body = `// Generated by tools/art3d.mjs. Do not edit. Emoji -> file name in public/art3d (Fluent Emoji 3D, MIT).\nexport const ART3D: Record<string, string> = ${JSON.stringify(map, null, 0).replace(/","/g, '",\n  "')}\n\n/** Emoji the app uses that have no 3D picture (they stay as emoji). */\nexport const NO_ART3D: string[] = ${JSON.stringify(missing)}\n`;
fs.writeFileSync(path.join(ROOT, 'src/play/art3d.generated.ts'), body);
fs.writeFileSync(path.join(OUT, 'CREDITS.md'), '# 3D pictures\n\nMicrosoft Fluent Emoji 3D (MIT, https://github.com/microsoft/fluentui-emoji), 256 px WebP files from the npm\npackage @lobehub/fluent-emoji-3d@1.1.0 (MIT), named by Unicode code points. Built by `tools/art3d.mjs`, which\nships only the pictures the app uses.\n');
const bytes = fs.readdirSync(OUT).reduce((s, f) => s + fs.statSync(path.join(OUT, f)).size, 0);
console.log(`used ${used.size} distinct emoji, ${Object.keys(map).length} with a 3D picture (${(bytes / 1024).toFixed(0)} kB), missing: ${missing.join(' ') || 'none'}`);
